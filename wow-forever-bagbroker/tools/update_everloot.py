#!/usr/bin/env python3
"""Downloads Everloot's crowd-sourced WoW Forever drop rates and writes BagBroker/EverlootData.lua.

Everloot (https://everloot.app) publishes what players looted in WoW Forever: for each source
creature and item, the number of loot windows opened and how many held the item. BagBroker weights
these observations by their count against the vanilla database and your own kills.
Data: Everloot, CC BY-SA 4.0 (credit is written into the generated file).

The game cannot download anything itself, so run this script to refresh the data (it needs only
Python 3), schedule it (see README), or install the zip the scheduled GitHub workflow publishes.

Usage
  python3 update_everloot.py                       # writes ../BagBroker/EverlootData.lua
  python3 update_everloot.py --out "C:/Program Files (x86)/World of Warcraft/_forever_/Interface/AddOns/BagBroker/EverlootData.lua"
"""
import argparse
import datetime
import json
import os
import subprocess
import sys
import time
import urllib.request

API = "https://everloot.app/api/rollups/drops"
PAGE = 500
MIN_REPORTERS = 2   # a rate seen by a single install is ignored


def fetch_json(url, tries=4):
    last = None
    for attempt in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "BagBroker-updater/1.0", "Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=60) as resp:
                return json.load(resp)
        except Exception as exc:  # network or TLS issue: retry, then fall back to curl
            last = exc
            try:
                out = subprocess.run(["curl", "-sSfL", "--max-time", "60", url], check=True, capture_output=True)
                return json.loads(out.stdout)
            except Exception as exc2:
                last = exc2
            time.sleep(2 ** attempt)
    raise RuntimeError("could not fetch %s: %s" % (url, last))


def download():
    rates, zeros, meta = [], [], None
    offset = 0
    while True:
        page = fetch_json("%s?offset=%d&limit=%d" % (API, offset, PAGE))
        if page.get("unreachable"):
            raise RuntimeError("Everloot storage unreachable; keeping the existing file")
        meta = meta or page
        rates.extend(page.get("rates") or [])
        zeros.extend(page.get("measuredZeros") or [])
        if not page.get("next"):
            break
        offset += PAGE
        time.sleep(1.0)  # stay well inside the public rate limit
    return rates, zeros, meta


def build(rates, zeros):
    """{npcID: {"kills": n, "reporters": r, "items": {itemID: drops}}} for creature sources."""
    npcs = {}
    for r in rates + zeros:
        npc = r.get("sourceNpcId")
        if not npc or (r.get("reporters") or 0) < MIN_REPORTERS:
            continue
        entry = npcs.setdefault(npc, {"kills": 0, "reporters": 0, "items": {}})
        entry["kills"] = max(entry["kills"], r.get("kills") or 0)
        entry["reporters"] = max(entry["reporters"], r.get("reporters") or 0)
        if r.get("itemId") and r.get("drops"):
            entry["items"][r["itemId"]] = r["drops"]
    return {k: v for k, v in npcs.items() if v["kills"] > 0}


def write(path, npcs, meta):
    as_of = (meta.get("stats") or {}).get("dataAsOf") or meta.get("dataAsOf") or meta.get("generatedAt") or ""
    credit = (meta.get("attribution") or {}).get("credit") or "Data from Everloot (https://everloot.app), CC BY-SA 4.0."
    lines = [
        "-- AUTO GENERATED by tools/update_everloot.py. Do not edit; rerun the script to refresh.",
        "-- " + credit + " https://creativecommons.org/licenses/by-sa/4.0/",
        "-- npcs[npcID] = { lootWindows, reporters, itemID, drops, itemID, drops, ... }",
        "local _, ns = ...",
        "ns.EverlootDB = {",
        'asOf = "%s",' % as_of[:19],
        'built = "%s",' % datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S"),
        "credit = %s," % json.dumps(credit),
        "npcs = {",
    ]
    for npc in sorted(npcs):
        e = npcs[npc]
        flat = ",".join("%d,%d" % (i, d) for i, d in sorted(e["items"].items()))
        lines.append("[%d]={%d,%d%s}," % (npc, e["kills"], e["reporters"], ("," + flat) if flat else ""))
    lines += ["},", "}", ""]
    content = "\n".join(lines)

    def without_stamp(text):
        return "\n".join(l for l in text.splitlines() if not l.startswith("built = "))

    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            if without_stamp(f.read()) == without_stamp(content):
                return False  # same data: leave the file untouched
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(content)
    os.replace(tmp, path)
    return True


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(here, "..", "BagBroker", "EverlootData.lua"))
    args = ap.parse_args()
    rates, zeros, meta = download()
    npcs = build(rates, zeros)
    changed = write(args.out, npcs, meta)
    windows = sum(e["kills"] for e in npcs.values())
    print("Everloot: %d rows, %d creatures kept (%d loot windows), data as of %s -> %s%s" % (
        len(rates) + len(zeros), len(npcs), windows, (meta.get("stats") or {}).get("dataAsOf"),
        os.path.abspath(args.out), "" if changed else " (unchanged)"))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("update failed: %s" % exc, file=sys.stderr)
        sys.exit(1)
